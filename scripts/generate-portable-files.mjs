#!/usr/bin/env node
/**
 * Write portable/ launchers and README (release package).
 * Called from scripts/prepare-portable.mjs after dist/ is copied.
 */
import { writeFile, chmod } from "node:fs/promises";
import { join } from "node:path";

export const PORTABLE_PORT = 8080;
export const PORTABLE_APP_URL = `http://127.0.0.1:${PORTABLE_PORT}/index.html`;

function windowsBat() {
  return `@echo off
setlocal
cd /d "%~dp0"

set PORT=${PORTABLE_PORT}
set SERVE=server\\win\\miniserve.exe

if not exist "%SERVE%" (
  echo Missing %SERVE%
  echo This portable package is incomplete. Re-download the release or rebuild with: npm run build:portable
  pause
  exit /b 1
)

if not exist "dist\\index.html" (
  echo Missing dist\\index.html
  echo This portable package is incomplete. Re-download the release or rebuild with: npm run build:portable
  pause
  exit /b 1
)

echo Shooting Script Liner - ${PORTABLE_APP_URL}
echo Close this window to stop the server.
start "" "${PORTABLE_APP_URL}"
"%SERVE%" dist -p %PORT% --interfaces 127.0.0.1
`;
}

function macCommand() {
  return `#!/bin/bash
cd "$(dirname "$0")"

PORT=${PORTABLE_PORT}
ARCH=$(uname -m)
case "$ARCH" in
  arm64|aarch64) SERVE="server/mac-arm64/miniserve" ;;
  *) SERVE="server/mac-x64/miniserve" ;;
esac

if [[ ! -f "$SERVE" ]]; then
  echo "Missing $SERVE"
  echo "This portable package is incomplete. Re-download the release or rebuild with: npm run build:portable"
  read -r -p "Press Enter to close..."
  exit 1
fi

if [[ ! -f dist/index.html ]]; then
  echo "Missing dist/index.html"
  echo "This portable package is incomplete. Re-download the release or rebuild with: npm run build:portable"
  read -r -p "Press Enter to close..."
  exit 1
fi

chmod +x "$SERVE" 2>/dev/null || true

echo "Shooting Script Liner - ${PORTABLE_APP_URL}"
echo "Close this window to stop the server."
open "${PORTABLE_APP_URL}" 2>/dev/null || true
exec "./$SERVE" dist -p "$PORT" --interfaces 127.0.0.1
`;
}

function linuxSh() {
  return `#!/bin/bash
cd "$(dirname "$0")"

PORT=${PORTABLE_PORT}
SERVE="server/linux-x64/miniserve"

if [[ ! -f "$SERVE" ]]; then
  echo "Missing $SERVE"
  echo "This portable package is incomplete. Re-download the release or rebuild with: npm run build:portable"
  exit 1
fi

if [[ ! -f dist/index.html ]]; then
  echo "Missing dist/index.html"
  echo "This portable package is incomplete. Re-download the release or rebuild with: npm run build:portable"
  exit 1
fi

chmod +x "$SERVE" 2>/dev/null || true

echo "Shooting Script Liner - ${PORTABLE_APP_URL}"
echo "Press Ctrl+C to stop the server."
xdg-open "${PORTABLE_APP_URL}" 2>/dev/null || sensible-browser "${PORTABLE_APP_URL}" 2>/dev/null || true
exec "./$SERVE" dist -p "$PORT" --interfaces 127.0.0.1
`;
}

function readme() {
  return `# Portable Shooting Script Liner

Offline package: local web server + built app. No internet required after this folder is prepared.

## Run

| OS | Start script |
|----|----------------|
| **Windows** | Double-click \`Start-Windows.bat\` |
| **macOS** | Double-click \`Start-macOS.command\` |
| **Linux** | Run \`./start-linux.sh\` |

Your browser opens **${PORTABLE_APP_URL}**. Close the terminal window to stop the server.

## Copy to USB

Copy this entire folder (including \`dist/\`, \`server/\`, and the start script for each OS you need). Works offline on any machine that matches a bundled server binary.

## Troubleshooting

- **Port in use** — Edit \`PORT=${PORTABLE_PORT}\` in the start script (the server uses the same port via \`-p\`).
- **macOS “cannot be opened”** — Right-click the \`.command\` file → Open, or run: \`xattr -cr server/mac-arm64 server/mac-x64\`
- **Missing files** — Re-download the release or rebuild from source with \`npm run build:portable\`.
- **Fonts** — Must be present under \`dist/fonts/\` (included in official builds).

## Layout

\`\`\`text
portable/
  dist/              # built app
  server/
    win/miniserve.exe
    mac-arm64/miniserve
    mac-x64/miniserve
    linux-x64/miniserve
  Start-Windows.bat
  Start-macOS.command
  start-linux.sh
\`\`\`

_Generated by \`npm run build:portable\`. Do not edit by hand — changes are overwritten on the next build._
`;
}

/**
 * @param {string} portableRoot - absolute path to portable/
 */
export async function generatePortableFiles(portableRoot) {
  const files = [
    { path: join(portableRoot, "Start-Windows.bat"), content: windowsBat() },
    { path: join(portableRoot, "Start-macOS.command"), content: macCommand(), executable: true },
    { path: join(portableRoot, "start-linux.sh"), content: linuxSh(), executable: true },
    { path: join(portableRoot, "README.md"), content: readme() },
  ];

  for (const { path, content, executable } of files) {
    await writeFile(path, content, "utf8");
    if (executable && process.platform !== "win32") {
      await chmod(path, 0o755);
    }
  }

  return files.map((f) => f.path);
}
